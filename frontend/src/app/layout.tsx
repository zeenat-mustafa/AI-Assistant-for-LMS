import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

import { AuthProvider } from "@/lib/auth/auth-context";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "AI Assistant for LMS",
  description: "Instructor-directed AI grading assistant for Jupyter notebook assignments.",
};

/**
 * Root layout stays a Server Component; `AuthProvider` is the client
 * boundary. The provider only holds session state — per the Next.js docs,
 * the actual access check happens in `RequireAuth` inside each protected
 * page, because layouts do not re-render on navigation.
 */
export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <AuthProvider>{children}</AuthProvider>
      </body>
    </html>
  );
}
